const assert = require('node:assert/strict');
const {parseURLs, buildQueue, makeReport, compatible, clientReport, aiExport, websiteReport, websiteData} = require('../app.js');
assert.deepEqual(parseURLs('https://example.com\nhttps://example.com/\nhttps://example.org'), ['https://example.com/', 'https://example.org/']);
assert.throws(() => parseURLs('javascript:alert(1)'));
assert.throws(() => parseURLs('https://user:pass@example.com'));
assert.equal(buildQueue(['https://a.test/','https://b.test/'],'both').length,4);
assert.deepEqual(buildQueue(['https://a.test/'],'both').map(x => x.strategy),['mobile','desktop']);
assert.deepEqual(buildQueue(['https://a.test/'],'desktop').map(x => x.strategy),['desktop']);
assert.deepEqual(parseURLs('https://example.com/%d8%a2\nhttps://example.com/%D8%A2'),['https://example.com/%D8%A2']);
const data = {lighthouseResult:{fetchTime:'2026-10-31T00:00:00Z',categories:{performance:{score:.76,auditRefs:[{id:'render-blocking-insight',group:'insights'},{id:'passed-insight',group:'insights'},{id:'legacy',group:'load-opportunities'}]}},audits:{'render-blocking-insight':{title:'Reduce blocking',description:'Try this.',score:0,displayValue:'Save 1 s',details:{headings:[{key:'url',label:'URL'}],items:[{url:'https://example.com/app.js'}]}},'passed-insight':{title:'Passed',score:1},legacy:{title:'Old opportunity',score:.5},'largest-contentful-paint':{title:'Largest Contentful Paint',displayValue:'2.5 s'}}}, loadingExperience:{metrics:{LARGEST_CONTENTFUL_PAINT_MS:{percentile:1900}}}};
const before = makeReport(data,'https://example.com/','mobile');
const newer = structuredClone(data); newer.lighthouseResult.fetchTime = '2026-11-01T00:00:00Z'; newer.lighthouseResult.categories.performance.score = .90; newer.lighthouseResult.audits['largest-contentful-paint'].displayValue = '1.8 s';
const after = makeReport(newer,'https://example.com/','mobile');
assert.equal(before.score,76);
assert.deepEqual(before.recommendations.map(a => a.title), ['Reduce blocking','Old opportunity']);
assert.equal(before.googleResponse, data);
const unusual = structuredClone(data); unusual.lighthouseResult.audits['render-blocking-insight'].details.items = {type:'not-an-array'};
assert.doesNotThrow(() => makeReport(unusual, 'https://example.com/', 'mobile'));
assert.equal(compatible(before,after), true);
assert.equal(compatible(before,{...after,strategy:'desktop'}), false);
const html = clientReport(before,after,'Optimized <images>');
assert.match(html, /افزایش ۱۴ امتیاز/);
assert.match(html, /lang="fa" dir="rtl"/);
assert.match(html, /score-card good/);
assert.match(html, /score-card medium/);
assert.doesNotMatch(html, /برای این دستگاه هنوز آزمایشی ثبت نشده است/);
assert.match(html, /۲٫۵ ثانیه/); assert.match(html, /۱٫۸ ثانیه/);
assert.match(html, /Optimized &lt;images&gt;/);
assert.doesNotMatch(html, /Optimized <images>/);
const result = JSON.parse(JSON.stringify(aiExport(before,after,'Optimized images')));
assert.deepEqual(result.before.googleResponse,data);
assert.equal(result.after.googleResponse.lighthouseResult.audits['render-blocking-insight'].details.items[0].url,'https://example.com/app.js');
assert.equal(result.before.googleResponse.loadingExperience.metrics.LARGEST_CONTENTFUL_PAINT_MS.percentile,1900);
assert.equal(aiExport({...before,googleResponse:undefined},after,'').before.googleResponse,null);
assert.throws(() => clientReport(before,{...after,url:'https://other.example/'},''), /same URL/);
assert.throws(() => makeReport({lighthouseResult:{runtimeError:{message:'failed'}}},'https://example.com','mobile'), /failed/);
const desktop = makeReport(data,'https://example.com/','desktop');
const secondPage = makeReport(data,'https://example.com/shop/','mobile');
const comparisons = [{url:before.url,strategy:'mobile',before,after,notes:'Optimized images'}, {url:desktop.url,strategy:'desktop',before:desktop,after:null,notes:''}, {url:secondPage.url,strategy:'mobile',before:secondPage,after:null,notes:''}];
const full = websiteReport('example.com',comparisons);
assert.match(full,/https:\/\/example.com\/shop\//);
assert.match(full,/تلفن همراه/); assert.match(full,/رایانه/);
assert.match(full,/نتایج پس از بهینه سازی در اینجا قرار خواهد گرفت/);
assert.match(full,/برای این دستگاه هنوز آزمایشی ثبت نشده است/); assert.match(full,/افزایش ۱۴ امتیاز/);
assert.match(full,/موارد قابل بررسی/);
assert.match(websiteReport('example.com',[{url:before.url,strategy:'mobile',before:{...before,score:0},after:null,notes:''}]), /score-card poor/);
assert.doesNotMatch(full,/Old opportunity/);
const fullData = JSON.parse(JSON.stringify(websiteData('example.com',comparisons,[before,after,desktop,secondPage])));
assert.equal(fullData.reports.length,4);
assert.deepEqual(fullData.reports[0].googleResponse,data);
assert.equal(fullData.comparisons[1].afterId,null);
assert.equal(fullData.comparisons[0].afterId,after.id);
console.log('All checks passed');
